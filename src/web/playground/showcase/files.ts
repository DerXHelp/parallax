export const REMINDER_SERVICE = lines(
  "import 'package:flutter_local_notifications/flutter_local_notifications.dart';",
  "import 'package:timezone/data/latest_all.dart' as tz_data;",
  "import 'package:timezone/timezone.dart' as tz;",
  '',
  "import '../models/event.dart';",
  "import 'settings_repository.dart';",
  '',
  '/// Local reminders for club events: 24 h and 1 h before.',
  'class ReminderService {',
  '  ReminderService(this._plugin, this._settings);',
  '',
  '  final FlutterLocalNotificationsPlugin _plugin;',
  '  final SettingsRepository _settings;',
  '',
  '  static const _offsets = [Duration(days: 1), Duration(hours: 1)];',
  '',
  '  static const _android = AndroidNotificationDetails(',
  "    'events',",
  "    'Termine',",
  "    channelDescription: 'Training, Spiele und Versammlungen',",
  '    importance: Importance.high,',
  '    priority: Priority.high,',
  '  );',
  '',
  '  Future<void> init() async {',
  '    tz_data.initializeTimeZones();',
  "    tz.setLocalLocation(tz.getLocation('Europe/Berlin'));",
  '    await _plugin.initialize(',
  '      const InitializationSettings(',
  "        android: AndroidInitializationSettings('ic_reminder'),",
  '        iOS: DarwinInitializationSettings(),',
  '      ),',
  '    );',
  '  }',
  '',
  '  /// Replaces every reminder of [event]; does nothing while reminders are off.',
  '  Future<void> schedule(Event event) async {',
  '    await cancel(event);',
  '    if (!await _settings.remindersEnabled()) return;',
  '',
  '    for (final (index, offset) in _offsets.indexed) {',
  '      final at = event.start.subtract(offset);',
  '      if (at.isBefore(DateTime.now())) continue;',
  '      await _plugin.zonedSchedule(',
  '        _notificationId(event, index),',
  '        event.title,',
  '        _body(event, offset),',
  '        tz.TZDateTime.from(at, tz.local),',
  '        const NotificationDetails(android: _android, iOS: DarwinNotificationDetails()),',
  '        androidScheduleMode: AndroidScheduleMode.inexactAllowWhileIdle,',
  '        payload: event.id,',
  '      );',
  '    }',
  '  }',
  '',
  '  Future<void> cancel(Event event) async {',
  '    for (var index = 0; index < _offsets.length; index++) {',
  '      await _plugin.cancel(_notificationId(event, index));',
  '    }',
  '  }',
  '',
  '  String _body(Event event, Duration offset) {',
  "    final when = offset.inHours >= 24 ? 'Morgen' : 'In einer Stunde';",
  "    return '$when · ${event.location}';",
  '  }',
  '',
  '  int _notificationId(Event event, int index) =>',
  '      (event.id.hashCode & 0x0fffffff) * _offsets.length + index;',
  '}',
);

