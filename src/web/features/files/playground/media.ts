/**
 * Generated media of the playground (no server behind Vite): an SVG as `data:` URL for images
 * (page CSP `img-src data:`) and a one-page PDF as `blob:` URL for the PDF frame (the Vite dev
 * server sends no page CSP; the real app frames GET /api/file of its own origin).
 */

/** The fake "diagram.png" as SVG (demo content, like the transcript's demo images). */
export function demoImageUrl(): string {
  const svg = [
    '<svg xmlns="http://www.w3.org/2000/svg" width="960" height="540" viewBox="0 0 960 540">',
    '<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="hsl(205 60% 52%)"/><stop offset="1" stop-color="hsl(255 45% 32%)"/></linearGradient></defs>',
    '<rect width="100%" height="100%" fill="url(#g)"/>',
    '<g fill="rgba(255,255,255,0.22)" stroke="white" stroke-width="3">',
    '<rect x="80" y="200" width="200" height="120" rx="14"/><rect x="380" y="200" width="200" height="120" rx="14"/><rect x="680" y="200" width="200" height="120" rx="14"/>',
    '</g>',
    '<g stroke="white" stroke-width="4"><line x1="280" y1="260" x2="380" y2="260"/><line x1="580" y1="260" x2="680" y2="260"/></g>',
    '<g font-family="sans-serif" font-size="26" fill="white" text-anchor="middle">',
    '<text x="180" y="270">Browser</text><text x="480" y="270">Server</text><text x="780" y="270">claude</text>',
    '<text x="480" y="110" font-size="40">diagram.png · 960 × 540</text>',
    '</g></svg>',
  ].join('');
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

/** A minimal valid one-page PDF (Helvetica text, correct xref offsets). */
export function demoPdfBytes(title = 'Sample specification'): Uint8Array<ArrayBuffer> {
  const content = `BT /F1 28 Tf 72 760 Td (${title}) Tj ET BT /F1 14 Tf 72 720 Td (Generated by the Parallax playground.) Tj ET`;
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
    `<< /Length ${String(content.length)} >>\nstream\n${content}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];
  let body = '%PDF-1.4\n';
  const offsets: number[] = [];
  objects.forEach((object, index) => {
    offsets.push(body.length);
    body += `${String(index + 1)} 0 obj\n${object}\nendobj\n`;
  });
  const xref = body.length;
  body += `xref\n0 ${String(objects.length + 1)}\n0000000000 65535 f \n`;
  for (const offset of offsets) body += `${String(offset).padStart(10, '0')} 00000 n \n`;
  body += `trailer\n<< /Size ${String(objects.length + 1)} /Root 1 0 R >>\nstartxref\n${String(xref)}\n%%EOF\n`;
  return new TextEncoder().encode(body);
}

let pdfUrl: string | null = null;

/** URL of the content of `path` for `<img>`/`<iframe>`/download in the playground. */
export function demoFileUrl(path: string): string {
  const extension = windowsPathExtension(path);
  if (extension === 'pdf') {
    pdfUrl ??= URL.createObjectURL(new Blob([demoPdfBytes()], { type: 'application/pdf' }));
    return pdfUrl;
  }
  if (extension === 'png' || extension === 'svg') return demoImageUrl();
  return `data:text/plain;charset=utf-8,${encodeURIComponent(path)}`;
}
